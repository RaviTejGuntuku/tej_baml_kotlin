    /// Helper: build IR, convert to Kotlin types, render templates, return all generated files.
    fn render_all(baml: &str) -> Vec<(String, String)> {
        let ir = make_test_ir(baml).expect("Valid BAML");
        let ir = std::sync::Arc::new(ir);
        let pkg = CurrentRenderPackage::new("baml_client", ir.clone());

        let mut files = Vec::new();

        // Functions
        let functions: Vec<_> = ir
            .functions
            .iter()
            .map(|f| fn_conv::ir_function_to_kotlin(f, &pkg))
            .collect();
        files.push((
            "BamlFunctions.kt".to_string(),
            render_functions(&functions, &pkg).unwrap(),
        ));
        files.push((
            "BamlStreamFunctions.kt".to_string(),
            render_functions_stream(&functions, &pkg).unwrap(),
        ));
        files.push((
            "BamlParseFunctions.kt".to_string(),
            render_functions_parse(&functions, &pkg).unwrap(),
        ));

        // Classes
        let kotlin_classes: Vec<_> = ir
            .walk_classes()
            .map(|c| classes::ir_class_to_kotlin(c.item, &pkg))
            .collect();

        // Enums
        let kotlin_enums: Vec<_> = ir
            .walk_enums()
            .map(|e| enums::ir_enum_to_kotlin(e.item, &pkg))
            .collect();

        // Unions
        let kotlin_unions: Vec<_> = {
            let mut unions: Vec<_> = ir
                .walk_all_non_streaming_unions()
                .flat_map(|t| unions::ir_union_to_kotlin(&t, &pkg))
                .collect();
            unions.sort_by_key(|u| u.name.clone());
            unions.dedup_by_key(|u| u.name.clone());
            unions
        };

        // Type aliases
        let type_aliases: Vec<_> = ir.walk_type_aliases().collect();
        let mut kotlin_type_aliases: Vec<_> = type_aliases
            .iter()
            .map(|c| type_aliases::ir_type_alias_to_kotlin(c.item, &pkg, None))
            .collect();
        kotlin_type_aliases.sort_by(|a, b| a.name.cmp(&b.name));

        // Stream unions
        let stream_unions: Vec<_> = {
            let mut unions: Vec<_> = ir
                .walk_all_streaming_unions()
                .flat_map(|t| unions::ir_union_to_kotlin_stream(&t, &pkg))
                .collect();
            unions.sort_by_key(|u| u.name.clone());
            unions.dedup_by_key(|u| u.name.clone());
            unions
        };

        // Type map
        files.push((
            "BamlTypeMap.kt".to_string(),
            render_type_map(&kotlin_classes, &kotlin_enums, &kotlin_unions, &stream_unions, &pkg)
                .unwrap(),
        ));

        // Types package
        pkg.set("baml_client.types");
        files.push((
            "types/Classes.kt".to_string(),
            render_kotlin_types(&kotlin_classes, &pkg).unwrap(),
        ));
        files.push((
            "types/Enums.kt".to_string(),
            render_kotlin_types(&kotlin_enums, &pkg).unwrap(),
        ));
        files.push((
            "types/Unions.kt".to_string(),
            render_kotlin_types(&kotlin_unions, &pkg).unwrap(),
        ));
        files.push((
            "types/TypeAliases.kt".to_string(),
            render_kotlin_types(&kotlin_type_aliases, &pkg).unwrap(),
        ));

        // Stream types package
        let stream_classes: Vec<_> = ir
            .walk_classes()
            .map(|c| classes::ir_class_to_kotlin_stream(c.item, &pkg))
            .collect();
        let mut stream_type_aliases: Vec<_> = type_aliases
            .iter()
            .map(|c| type_aliases::ir_type_alias_to_kotlin_stream(c.item, &pkg, None))
            .collect();
        stream_type_aliases.sort_by(|a, b| a.name.cmp(&b.name));

        pkg.set("baml_client.stream_types");
        files.push((
            "stream_types/Classes.kt".to_string(),
            render_kotlin_stream_types(&stream_classes, &pkg).unwrap(),
        ));
        files.push((
            "stream_types/Unions.kt".to_string(),
            render_kotlin_stream_types(&stream_unions, &pkg).unwrap(),
        ));
        files.push((
            "stream_types/TypeAliases.kt".to_string(),
            render_kotlin_stream_types(&stream_type_aliases, &pkg).unwrap(),
        ));

        files
    }

    fn get_file<'a>(files: &'a [(String, String)], name: &str) -> &'a str {
        files
            .iter()
            .find(|(n, _)| n == name)
            .map(|(_, content)| content.as_str())
            .unwrap_or_else(|| panic!("File '{}' not found", name))
    }

    // ==================== BASIC RENDERING ====================

    #[test]
    fn test_render_simple_class() {
        let files = render_all(
            r##"
            class Person {
                name string
                age int
            }
            function Greet(p: Person) -> string {
                client "openai/gpt-4o"
                prompt #"Hello {{ p.name }}"#
            }
            "##,
        );

        let classes = get_file(&files, "types/Classes.kt");
        assert!(classes.contains("data class Person("), "Missing Person class: {}", classes);
        assert!(classes.contains("val name: String"), "Missing name field");
        assert!(classes.contains("val age: Long"), "Missing age field");

        let stream_classes = get_file(&files, "stream_types/Classes.kt");
        assert!(stream_classes.contains("data class Person("), "Missing stream Person");
        assert!(
            stream_classes.contains("val name: String?"),
            "Stream fields should be nullable: {}",
            stream_classes
        );
        assert!(
            stream_classes.contains("val age: Long?"),
            "Stream age should be nullable"
        );
    }

