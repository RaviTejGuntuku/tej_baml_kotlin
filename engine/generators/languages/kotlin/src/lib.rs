#[derive(Default)]
pub struct KotlinLanguageFeatures;

impl LanguageFeatures for KotlinLanguageFeatures {
    const CONTENT_PREFIX: &'static str = r#"
// ----------------------------------------------------------------------------
//
//  Welcome to Baml! To use this generated code, add the BAML Kotlin SDK
//  dependency to your project.
//
// ----------------------------------------------------------------------------

// This file was generated by BAML: please do not edit it. Instead, edit the
// BAML files and re-generate this code using: baml-cli generate
        "#;

    fn name() -> &'static str {
        "kotlin"
    }

    fn generate_sdk_files(
        &self,
        collector: &mut FileCollector<Self>,
        ir: std::sync::Arc<IntermediateRepr>,
        args: &GeneratorArgs,
    ) -> Result<(), anyhow::Error> {
        let pkg = package::CurrentRenderPackage::new("baml_client", ir.clone());
        let file_map = args.file_map_as_json_string()?;

        // Source map
        collector.add_file("BamlSourceMap.kt", render_source_files(file_map)?)?;

        // Runtime initialization
        collector.add_file("BamlRuntimeInit.kt", render_runtime_code(&pkg)?)?;

        // Functions
        let functions = ir
            .functions
            .iter()
            .map(|f| ir_to_kotlin::functions::ir_function_to_kotlin(f, &pkg))
            .collect::<Vec<_>>();
        collector.add_file("BamlFunctions.kt", render_functions(&functions, &pkg)?)?;
        collector.add_file(
            "BamlStreamFunctions.kt",
            render_functions_stream(&functions, &pkg)?,
        )?;
        collector.add_file(
            "BamlParseFunctions.kt",
            render_functions_parse(&functions, &pkg)?,
        )?;

        // Classes
        let kotlin_classes = ir
            .walk_classes()
            .map(|c| ir_to_kotlin::classes::ir_class_to_kotlin(c.item, &pkg))
            .collect::<Vec<_>>();

        // Enums
        let enums = ir
            .walk_enums()
            .map(|e| ir_to_kotlin::enums::ir_enum_to_kotlin(e.item, &pkg))
            .collect::<Vec<_>>();

        // Unions
        let unions = {
            let mut unions = ir
                .walk_all_non_streaming_unions()
                .flat_map(|t| ir_to_kotlin::unions::ir_union_to_kotlin(&t, &pkg))
                .collect::<Vec<_>>();
            unions.sort_by_key(|u| u.name.clone());
            unions.dedup_by_key(|u| u.name.clone());
            unions
        };

        // Type aliases
        let type_aliases = ir.walk_type_aliases().collect::<Vec<_>>();

        let invalid_cycles = ir
            .structural_recursive_alias_cycles()
            .iter()
            .filter(|&cycle| {
                cycle.iter().all(|(_, field_type)| {
                    field_type
                        .find_if(
                            &|t| match t {
                                TypeGeneric::Class { .. } => true,
                                TypeGeneric::Enum { .. } => true,
                                TypeGeneric::Literal(..) => true,
                                TypeGeneric::Primitive(TypeValue::Null, ..) => false,
                                TypeGeneric::Primitive(..) => true,
                                _ => false,
                            },
                            true,
                        )
                        .is_empty()
                })
            })
            .flat_map(|cycle| {
                let keys = cycle.keys().cloned().collect::<Vec<_>>();
                let first_key = keys[0].clone();
                keys.into_iter().map(move |k| (k, first_key.clone()))
            })
            .collect::<baml_types::BamlMap<_, _>>();

        let mut kotlin_type_aliases = type_aliases
            .iter()
            .map(|c| {
                ir_to_kotlin::type_aliases::ir_type_alias_to_kotlin(
                    c.item,
                    &pkg,
                    invalid_cycles.get(&c.elem().name),
                )
            })
            .collect::<Vec<_>>();
        kotlin_type_aliases.sort_by(|a, b| a.name.cmp(&b.name));

        // Stream unions
        let stream_unions = {
            let mut unions = ir
                .walk_all_streaming_unions()
                .flat_map(|t| ir_to_kotlin::unions::ir_union_to_kotlin_stream(&t, &pkg))
                .collect::<Vec<_>>();
            unions.sort_by_key(|u| u.name.clone());
            unions.dedup_by_key(|u| u.name.clone());
            unions
        };

        // Type map
        collector.add_file(
            "BamlTypeMap.kt",
            render_type_map(&kotlin_classes, &enums, &unions, &stream_unions, &pkg)?,
        )?;

        // Types package
        pkg.set("baml_client.types");
        collector.add_file(
            "types/Classes.kt",
            render_kotlin_types(&kotlin_classes, &pkg)?,
        )?;
        collector.add_file("types/Enums.kt", render_kotlin_types(&enums, &pkg)?)?;
        collector.add_file("types/Unions.kt", render_kotlin_types(&unions, &pkg)?)?;
        collector.add_file(
            "types/TypeAliases.kt",
            render_kotlin_types(&kotlin_type_aliases, &pkg)?,
        )?;

        // Stream types package
        let stream_classes = ir
            .walk_classes()
            .map(|c| ir_to_kotlin::classes::ir_class_to_kotlin_stream(c.item, &pkg))
            .collect::<Vec<_>>();

        let mut stream_type_aliases = type_aliases
            .iter()
            .map(|c| {
                ir_to_kotlin::type_aliases::ir_type_alias_to_kotlin_stream(
                    c.item,
                    &pkg,
                    invalid_cycles.get(&c.elem().name),
                )
            })
            .collect::<Vec<_>>();
        stream_type_aliases.sort_by(|a, b| a.name.cmp(&b.name));

        pkg.set("baml_client.stream_types");
        collector.add_file(
            "stream_types/Classes.kt",
            render_kotlin_stream_types(&stream_classes, &pkg)?,
        )?;
        collector.add_file(
            "stream_types/Unions.kt",
            render_kotlin_stream_types(&stream_unions, &pkg)?,
        )?;
        collector.add_file(
            "stream_types/TypeAliases.kt",
            render_kotlin_stream_types(&stream_type_aliases, &pkg)?,
        )?;

        Ok(())
    }
}

